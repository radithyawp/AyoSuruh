  static String notificationText(String input) {
    if (!isEnglish || input.isEmpty) return input;

    final String? exact =
        _finalPolishEnglish[input] ??
        _productionEnglish[input] ??
        _exactEnglish[input];
    if (exact != null) return exact;

    RegExpMatch? match = RegExp(
      r'^(.+) mengajukan penawaran untuk pekerjaan "(.+)"\.$',
    ).firstMatch(input);
    if (match != null) {
      return '${match.group(1)} submitted an offer for "${match.group(2)}".';
    }
    match = RegExp(
      r'^Penawaranmu untuk pekerjaan "(.+)" telah diterima customer\.$',
    ).firstMatch(input);
    if (match != null) {
      return 'Your offer for "${match.group(1)}" was accepted by the Customer.';
    }
    match = RegExp(
      r'^Penawaranmu untuk pekerjaan "(.+)" belum dipilih customer\.$',
    ).firstMatch(input);
    if (match != null) {
      return 'Your offer for "${match.group(1)}" was not selected by the Customer.';
    }
    match = RegExp(
      r'^Mitra sedang menuju lokasi pekerjaan "(.+)"\.$',
    ).firstMatch(input);
    if (match != null) {
      return 'The Partner is heading to the location for "${match.group(1)}".';
    }
    match = RegExp(
      r'^Mitra sudah tiba untuk mengerjakan "(.+)"\.$',
    ).firstMatch(input);
    if (match != null) {
      return 'The Partner has arrived to work on "${match.group(1)}".';
    }
    match = RegExp(r'^Mitra mulai mengerjakan "(.+)"\.$').firstMatch(input);
    if (match != null) {
      return 'The Partner started working on "${match.group(1)}".';
    }
    match = RegExp(
      r'^Mitra menyatakan pekerjaan "(.+)" selesai\. Periksa hasil pekerjaannya\.$',
    ).firstMatch(input);
    if (match != null) {
      return 'The Partner marked "${match.group(1)}" as finished. Review the result.';
    }
    match = RegExp(
      r'^Mitra menyatakan pekerjaan "(.+)" selesai\. Periksa hasilnya\. Jika tidak ada tindakan, pekerjaan akan otomatis selesai dalam (\d+) jam setelah syarat pembayaran terpenuhi\.$',
    ).firstMatch(input);
    if (match != null) {
      return 'The Partner marked "${match.group(1)}" as finished. Review the result. If no action is taken, the job will be completed automatically in ${match.group(2)} hours after the payment requirements are met.';
    }

    return t(input);
  }

  static String t(String input) {
    if (input.isEmpty) return input;
    if (!isEnglish) {
      if (input.trim().toLowerCase() == 'design & coding') {
        return 'Desain & Pemrograman';
      }
      return input;
    }
    final String? finalPolish = _finalPolishEnglish[input];
    if (finalPolish != null) return finalPolish;
    final String? production = _productionEnglish[input];
    if (production != null) return production;
    final String? exact = _exactEnglish[input];
    if (exact != null) return exact;

    final String dynamicSystemCopy = _translateDynamicSystemCopy(input);
    if (dynamicSystemCopy != input) return dynamicSystemCopy;

    // Keep technical identifiers and URLs intact.
    if (input.startsWith('http://') ||
        input.startsWith('https://') ||
        input.startsWith('assets/') ||
        input.contains('@') && !input.contains(' ')) {
      return input;
    }

    // Only source-defined product copy may use phrase fallback. Dynamic user
    // content (names, job titles, chat messages, addresses, etc.) stays intact.
    if (!_knownAppCopy.contains(input)) return input;

    String output = input;
    final List<MapEntry<String, String>> entries =
        _phraseEnglish.entries.toList()
          ..sort((a, b) => b.key.length.compareTo(a.key.length));
    for (final MapEntry<String, String> entry in entries) {
      output = output.replaceAll(entry.key, entry.value);
    }
    return output;
  }
